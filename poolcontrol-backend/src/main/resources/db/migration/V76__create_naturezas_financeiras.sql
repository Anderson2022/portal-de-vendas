CREATE TABLE naturezas_financeiras (
    id UUID PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    codigo VARCHAR(30) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    tipo VARCHAR(30) NOT NULL,
    grupo VARCHAR(30) NOT NULL,
    natureza_pai_id UUID,
    movimento VARCHAR(10) NOT NULL CHECK (movimento IN ('ENTRADA', 'SAIDA', 'AMBOS')),
    impacta_fluxo_caixa BOOLEAN NOT NULL DEFAULT TRUE,
    impacta_dre BOOLEAN NOT NULL DEFAULT TRUE,
    impacta_resultado BOOLEAN NOT NULL DEFAULT TRUE,
    aceita_lancamento BOOLEAN NOT NULL DEFAULT TRUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ordem INTEGER NOT NULL DEFAULT 0,
    cor VARCHAR(30),
    icone VARCHAR(60),
    data_inicio DATE,
    data_fim DATE,
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_por BIGINT REFERENCES users(id),
    atualizado_por BIGINT REFERENCES users(id),
    UNIQUE (empresa_id, codigo),
    UNIQUE (id, empresa_id),
    FOREIGN KEY (natureza_pai_id, empresa_id) REFERENCES naturezas_financeiras(id, empresa_id),
    CHECK (data_fim IS NULL OR data_inicio IS NULL OR data_fim >= data_inicio),
    CHECK (tipo <> 'TRANSFERENCIA' OR (NOT impacta_dre AND NOT impacta_resultado AND movimento = 'AMBOS'))
);
